-- ROW LEVEL SECURITY
--
-- Enabled with NO policies. This is intentional and correct for
-- this app's architecture: the backend is the only thing that
-- talks to Supabase, always using the service_role key, which
-- bypasses RLS entirely regardless of policies. Enabling RLS with
-- zero policies denies all access to the anon/authenticated roles
-- — i.e. anyone using the public anon key directly (e.g. from
-- browser dev tools) gets nothing. That closes the "Unrestricted"
-- exposure without risking locking the backend out.
--
-- Only add real policies here if the browser ever needs to talk to
-- Supabase directly (e.g. Realtime subscriptions, a public
-- read-only page) — that path doesn't go through the backend, so
-- it would need its own scoped access rules.
-- ============================================================

