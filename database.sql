create index if not exists idx_stock_transactions_inventory
    on stock_transactions (inventory_id);

create index if not exists idx_stock_transactions_type
    on stock_transactions (transaction_type);

create index if not exists idx_stock_transactions_created_at
    on stock_transactions (created_at);


-- ------------------------------------------------------------
-- Trigger: auto-derive stock_transactions.restaurants_id from
-- the destination side of the transaction, and enforce that a
-- TRANSFER moves the same item name (not a rename). See the
-- "CROSS-RESTAURANT OWNERSHIP RULE" note at the top of this file.
--
-- BEFORE INSERT/UPDATE runs prior to constraint checking, so this
-- overwrites NEW.restaurants_id (even if the caller passed null or
-- some other value) before the `not null` constraint is evaluated
-- — the caller does not need to know or supply the correct
-- restaurant at all, only the correct kitchen_id/inventory_id.
-- ------------------------------------------------------------
create or replace function set_stock_transaction_restaurant()
returns trigger as $$
declare
    v_production_product text;
    v_kitchen_product text;
begin
    if new.transaction_type in ('TRANSFER', 'SELF_PRODUCE') then
        select restaurants_id into new.restaurants_id
        from kitchen_stock
        where kitchen_id = new.kitchen_id;
    elsif new.transaction_type = 'SALE' then
        select restaurants_id into new.restaurants_id
        from inventory
        where inventory_id = new.inventory_id;
    end if;

    if new.restaurants_id is null then
        raise exception
            'Could not derive restaurants_id for stock_transactions row (transaction_type=%, kitchen_id=%, inventory_id=%)',
            new.transaction_type, new.kitchen_id, new.inventory_id;
    end if;

    -- A TRANSFER must move the same item, not rename it —
    -- production_stock.product and kitchen_stock.product must match,
    -- even across a cross-restaurant transfer.
    if new.transaction_type = 'TRANSFER' then
        select product into v_production_product
        from production_stock
        where production_id = new.production_id;

        select product into v_kitchen_product
        from kitchen_stock
        where kitchen_id = new.kitchen_id;

        if v_production_product is distinct from v_kitchen_product then
            raise exception
                'Product name mismatch on TRANSFER: production_stock.product = %, kitchen_stock.product = % (production_id=%, kitchen_id=%). A transfer must move the same item, not rename it.',
                v_production_product, v_kitchen_product, new.production_id, new.kitchen_id;
        end if;
    end if;

    return new;
end;
$$ language plpgsql;

