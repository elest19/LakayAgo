-- ============================================================
-- Lakay Ago / Aroo — Combined Supabase PostgreSQL Schema
--
-- Modules:
-- 1. Attendance / Payroll / Leave
-- 2. Inventory: Production -> Kitchen -> Menu
-- 3. Sales
-- 4. Expenses
--
-- Restaurants:
-- - Aroo
-- - Lakay Ago
--
-- IMPORTANT INVENTORY RELATIONSHIP RULE:
-- Each restaurant has its own Production, Kitchen, and Inventory
-- records.
--
-- However, inventory relationships and stock transactions may
-- cross restaurant boundaries.
--
-- Example:
-- Aroo Kitchen can receive stock from Lakay Ago Production.
--
-- Therefore:
-- - restaurants_id identifies the restaurant that owns the row.
-- - kitchen_id / production_id / inventory_id identify the
-- specific related record.
-- - No composite same-restaurant foreign keys are used.
--
-- CROSS-RESTAURANT OWNERSHIP RULE (stock_transactions):
-- A cross-restaurant transfer touches two restaurants at once
-- (Production's and Kitchen's), but stock_transactions.restaurants_id
-- can only hold one value. To remove any ambiguity about which side
-- "wins", a trigger (see below, near the stock_transactions table)
-- always DERIVES restaurants_id from the destination side of the
-- transaction and overwrites whatever value was supplied:
-- - TRANSFER / SELF_PRODUCE: destination is the Kitchen, so
-- restaurants_id := kitchen_stock.restaurants_id for that kitchen_id.
-- - SALE: destination is the Menu (inventory), so
-- restaurants_id := inventory.restaurants_id for that inventory_id.
-- This makes the rule enforced by the database itself rather than
-- something every insert has to get right on its own — two different
-- inserts for the same real-world transfer can no longer disagree.
--
-- Passwords:
-- users.password must contain a bcrypt hash generated by the
-- application layer. Plaintext passwords must NEVER be stored.
--
-- RLS:
-- RLS is intentionally not enabled in this schema.
-- ============================================================


