-- ============================================================
-- 17. STOCK TRANSACTIONS
--
-- Cross-restaurant stock interaction is intentionally supported.
--
-- Example:
-- Aroo Kitchen can receive stock from Lakay Ago Production.
--
-- restaurants_id is NOT set by the caller — see the trigger
-- immediately below this table. It is always derived from the
-- destination side of the transaction: kitchen_stock's restaurant
-- for TRANSFER/SELF_PRODUCE, inventory's restaurant for SALE.
-- Whatever value is passed in on INSERT/UPDATE is overwritten, so
-- there is exactly one rule for "which restaurant owns this row",
-- enforced by the database rather than by application code.
-- ============================================================

create table if not exists stock_transactions (
    stock_transaction_id bigint generated always as identity primary key,

    restaurants_id bigint not null
        references restaurants(restaurants_id)
        on delete cascade,

    kitchen_id bigint
        references kitchen_stock(kitchen_id)
        on delete set null,

    production_id bigint
        references production_stock(production_id)
        on delete set null,

    inventory_id bigint
        references inventory(inventory_id)
        on delete set null,

    name text not null,

    transaction_type text not null
        check (
            transaction_type in (
                'TRANSFER',
                'SELF_PRODUCE',
                'SALE'
            )
        ),

    quantity numeric(10,2) not null
        check (quantity > 0),

    from_location text
        check (
            from_location in (
                'production',
                'kitchen'
            )
        ),

    to_location text
        check (
            to_location in (
                'kitchen',
                'menu'
            )
        ),

    performed_by text,

    created_at timestamptz not null default now(),

    -- TRANSFER:
    -- Production -> Kitchen
    --
    -- Production and Kitchen may belong to different restaurants.
    --
    -- SELF_PRODUCE:
    -- Internal Kitchen production
    --
    -- SALE:
    -- Kitchen -> Menu
    check (
        (
            transaction_type = 'TRANSFER'
            and from_location = 'production'
            and to_location = 'kitchen'
            and production_id is not null
            and kitchen_id is not null
            and inventory_id is null
        )
        or
        (
            transaction_type = 'SELF_PRODUCE'
            and from_location is null
            and to_location = 'kitchen'
            and production_id is null
            and kitchen_id is not null
            and inventory_id is null
        )
        or
        (
            transaction_type = 'SALE'
            and from_location = 'kitchen'
            and to_location = 'menu'
            and production_id is null
            and kitchen_id is not null
            and inventory_id is not null
        )
    )
);

comment on table stock_transactions is
'Restaurant-scoped audit trail of Production-to-Kitchen transfers, Kitchen self-production, and Menu sales. Production and Kitchen records may belong to different restaurants for cross-restaurant stock transfers. restaurants_id is auto-derived by trigger from the destination side — see trg_set_stock_transaction_restaurant below.';

create index if not exists idx_stock_transactions_restaurant
    on stock_transactions (restaurants_id);

create index if not exists idx_stock_transactions_kitchen
    on stock_transactions (kitchen_id);

create index if not exists idx_stock_transactions_production
