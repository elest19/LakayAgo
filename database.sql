-- ============================================================
-- 15. INVENTORY
--
-- Each linked Kitchen Stock item can correspond to exactly
-- one Inventory item.
--
-- IMPORTANT:
-- restaurants_id and kitchen_id are intentionally independent.
-- The referenced Kitchen Stock may belong to another restaurant.
-- ============================================================

create table if not exists inventory (
    inventory_id bigint generated always as identity primary key,

    restaurants_id bigint not null
        references restaurants(restaurants_id)
        on delete cascade,

    kitchen_id bigint
        references kitchen_stock(kitchen_id)
        on delete set null,

    name text,

    price numeric(10,2) not null
        check (price >= 0),

    stock numeric(10,2)
        check (stock is null or stock >= 0),

    category text not null
        check (category in ('Menu Item', 'Others')),

    is_archived boolean not null default false,

    created_at timestamptz not null default now(),

    -- Menu Item must be linked to Kitchen Stock.
    check (
        category <> 'Menu Item'
        or kitchen_id is not null
    ),

    -- Linked Inventory rows derive name/stock from Kitchen Stock.
    -- Standalone rows must contain their own name/stock.
    check (
        (
            kitchen_id is not null
            and name is null
            and stock is null
        )
        or
        (
            kitchen_id is null
            and name is not null
            and stock is not null
        )
    )
);

comment on table inventory is
'Restaurant-scoped Inventory catalog. A linked Inventory item derives its name and stock from a Kitchen Stock item. The Kitchen Stock may belong to a different restaurant because cross-restaurant relationships are intentionally allowed.';

-- One Kitchen Stock item -> one Inventory item.
